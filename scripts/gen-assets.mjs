function num(s) {
  return Number(s);
}
function attrs(tag) {
  const out = {};
  for (const m of tag.matchAll(/([a-zA-Z0-9-:]+)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}
function elementToPath(name, a) {
  switch (name) {
    case "path":
      return a.d;
    case "circle": {
      const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    }
    case "ellipse": {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx), ry = num(a.ry);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = "";
      for (let i = 0; i < pts.length; i += 2) d += `${i ? "L" : "M"}${pts[i]} ${pts[i + 1]}`;
      return name === "polygon" ? d + "Z" : d;
    }
    case "rect": {
      const x = num(a.x || 0), y = num(a.y || 0), w = num(a.width), h = num(a.height);
      const r = Math.min(num(a.rx || a.ry || 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
  }
  return "";
}

const icons = {};
for (const name of ICONS) {
  let svg;
  try {
    svg = readFileSync(join(root, "node_modules/lucide-static/icons", `${name}.svg`), "utf8");
  } catch {
    console.warn("missing icon", name);
    continue;
  }
  const parts = [];
  for (const m of svg.matchAll(/<(path|circle|ellipse|line|polyline|polygon|rect)\b([^>]*)\/?>/g)) {
    const d = elementToPath(m[1], attrs(m[2]));
    if (d) parts.push(d);
  }
  icons[name] = parts; // kept separate: a leading "m" in each part is absolute only at the start of its own path
}

function svgPaths(file) {
  const svg = readFileSync(join(root, "public/brand", file), "utf8");
  const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map((m) => attrs(m[1]).d).filter(Boolean);
  return { w: vb[2], h: vb[3], d: paths };
}
// The mark is two shapes: the top "flag" (index 0) and the S-flow (index 1); kept apart so they can animate separately.
const markSvg = readFileSync(join(root, "public/brand/icon-dark.svg"), "utf8");
const markParts = [...markSvg.matchAll(/<path\b([^>]*)>/g)].map((m) => attrs(m[1]).d);

const out = `// Generated by scripts/gen-assets.mjs. Do not edit by hand.
// Lucide icons (ISC licence) and the TaxStreem logo / icon mark as SVG path data.

export const ICONS: Record<string, string[]> = ${JSON.stringify(icons, null, 0)};

export const LOGO = ${JSON.stringify(svgPaths("logo-dark.svg"))};

export const MARK = ${JSON.stringify({ ...svgPaths("icon-dark.svg"), parts: markParts })};
`;
writeFileSync(join(root, "src/runtime/generated.ts"), out);
